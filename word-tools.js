function readWordSet(key) {
  try {
    return new Set(JSON.parse(localStorage.getItem(key) || "[]"));
  } catch {
    return new Set();
  }
}

function writeWordSet(key, set) {
  localStorage.setItem(key, JSON.stringify(Array.from(set)));
}

function toggleWordState(key, word) {
  const set = readWordSet(key);
  if (set.has(word)) {
    set.delete(word);
  } else {
    set.add(word);
  }
  writeWordSet(key, set);
  return set.has(word);
}

function escapeHtml(value) {
  return String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

