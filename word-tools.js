function regularVerbChange(word) {
  if (word.endsWith("e")) return `规则：直接 +d -> ${word}d`;
  if (/[^aeiou]y$/.test(word)) return `规则：y 变 i +ed -> ${word.slice(0, -1)}ied`;
  const doubleSet = new Set(["stop", "plan", "shop", "drop", "prefer"]);
  if (doubleSet.has(word)) return `规则：双写尾字母 +ed -> ${word}${word.at(-1)}ed`;
  return `规则：直接 +ed -> ${word}ed`;
}

function thirdPersonSingular(word) {
  const special = {
    be: "is",
    do: "does",
    go: "goes",
    have: "has",
  };
  if (special[word]) return special[word];
  if (/[^aeiou]y$/.test(word)) return `${word.slice(0, -1)}ies`;
  if (/(s|x|z|ch|sh|o)$/.test(word)) return `${word}es`;
  return `${word}s`;
}

function verbChangeInfo(english, pos) {
  const word = cleanLookupKey(english);
  if (!word || english.includes(" ") || english.includes("-")) return "";
  if (!pos.includes("v.") && pos !== "v.") return "";
  const auxiliaryForms = new Set(["am", "is", "are", "was", "were", "been", "being", "does", "did", "done", "has", "had"]);
  if (auxiliaryForms.has(word)) return "";
  const pastInfo = irregularVerbMap[word] || regularVerbChange(word);
  return `过去/分词：${pastInfo}；三单：${thirdPersonSingular(word)}`;
}

function collocationsFor(english) {
  const phrase = english.toLowerCase().trim();
  if (collocationMap[phrase]) return collocationMap[phrase];
  const word = cleanLookupKey(english);
  return collocationMap[word] || [];
}

